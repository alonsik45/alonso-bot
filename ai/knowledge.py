TWITCH_URL = "https://twitch.tv/alonsoroma22"


def render_bot_knowledge() -> str:
    """Собирает компактный текстовый блок BOT KNOWLEDGE для системного промпта."""
    lines = ["BOT KNOWLEDGE (реальная структура бота — используй только эти факты)", ""]

    lines.append("Команды:")
    for c in COMMANDS:
        lines.append(f"- {c['cmd']} ({c['who']}): {c['desc']}")
    lines.append("")

    lines.append("Главное меню:")
    for b in MAIN_MENU:
        lines.append(f"- «{b['button']}» → {b['leads_to']}")
    lines.append("")

    lines.append("Подробности по разделам:")
    for key, desc in SECTIONS.items():
        lines.append(f"- {desc}")
    lines.append("")

    lines.append(f"Ссылка на Twitch: {TWITCH_URL}")

    return "\n".join(lines)


def render_roma_knowledge(roma_data: dict) -> str:
    """Собирает текстовый блок ROMA KNOWLEDGE из data/roma_info.json."""
    lines = ["ROMA KNOWLEDGE (используй только эти факты о Роме, ничего не выдумывай)", ""]
    lines.append(f"Имя: {roma_data.get('name')}")
    lines.append(f"Кто он: {roma_data.get('who')}")
    lines.append(f"Чем занимается: {roma_data.get('activity')}")
    lines.append(f"Контент: {roma_data.get('content_style')}")
    lines.append(f"Возраст: {roma_data.get('age')}")
    lines.append(f"TikTok: {roma_data.get('tiktok_followers')} подписчиков")
    lines.append(f"Известен: {roma_data.get('known_for')}")

    pet = roma_data.get("pet", {})
    if pet:
        lines.append(
            f"Питомец: {pet.get('type')}, {pet.get('gender')}, зовут {pet.get('name')}, "
            f"возраст — {pet.get('age')}, окрас — {pet.get('color')}. "
            f"Про питомца можно говорить свободно и с теплом, это не деликатная тема."
        )

    schedule = roma_data.get("stream_schedule", {})
    days = ", ".join(schedule.get("days", []))
    lines.append(f"Расписание стримов: {days} в {schedule.get('time')} (по московскому времени проекта). "
                  f"{schedule.get('note', '')}")

    lines.append("")
    lines.append("Личное (упоминать кратко и уважительно, только если спросят напрямую, не поднимать самому):")
    if roma_data.get("relationship_status"):
        lines.append(f"- {roma_data['relationship_status']}")
    if roma_data.get("personal_note"):
        lines.append(f"- {roma_data['personal_note']}")

    links = roma_data.get("links", {})
    lines.append("")
    lines.append("Ссылки:")
    for name, url in links.items():
        lines.append(f"- {name}: {url}")

    return "\n".join(lines)
