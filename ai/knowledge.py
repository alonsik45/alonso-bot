def _game_numbers() -> str:
    """Цифры игры берём из game.py, чтобы подсказки Алонса не расходились с реальностью."""
    try:
        import game as g
        packs = ", ".join(f"{v[2]} — {v[0]} ⭐" for v in g.PACKS.values())
        return (f"Одна карточка за монеты стоит {g.OPEN_COST} 🪙. За звёзды: {packs}. "
                f"Всего в игре {len(g.CARDS)} карточек. ")
    except Exception:
        return ""


